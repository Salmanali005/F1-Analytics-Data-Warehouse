DROP TABLE IF EXISTS fact_race_results, fact_driver_standings, fact_driver_season_entry,
                     dim_date, dim_race, dim_season, dim_driver, dim_constructor,
                     dim_circuit, dim_status CASCADE;

CREATE TABLE dim_date (
    date_key INT PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    day SMALLINT,
    month SMALLINT,
    month_name VARCHAR(10),
    quarter SMALLINT,
    year SMALLINT,
    decade SMALLINT,
    weekday VARCHAR(10)
);

CREATE TABLE dim_race (
    race_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    race_id INT NOT NULL UNIQUE,
    race_name VARCHAR(100),
    round SMALLINT,
    season_year SMALLINT,
    race_date DATE
);

CREATE TABLE dim_season (
    season_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    season_year SMALLINT NOT NULL UNIQUE,
    era_label VARCHAR(50)
);

CREATE TABLE dim_driver (
    driver_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    driver_id INT NOT NULL UNIQUE,
    driver_ref VARCHAR(50),
    full_name VARCHAR(100),
    driver_code VARCHAR(3),
    date_of_birth DATE,
    nationality VARCHAR(50)
);

CREATE TABLE dim_constructor (
    constructor_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    constructor_id INT NOT NULL UNIQUE,
    constructor_ref VARCHAR(50),
    constructor_name VARCHAR(100),
    nationality VARCHAR(50)
);

CREATE TABLE dim_circuit (
    circuit_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    circuit_id INT NOT NULL UNIQUE,
    circuit_ref VARCHAR(50),
    circuit_name VARCHAR(100),
    location VARCHAR(100),
    country VARCHAR(60),
    latitude DECIMAL(9,6),
    longitude DECIMAL(9,6),
    altitude INT
);

CREATE TABLE dim_status (
    status_key INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    status_id INT NOT NULL UNIQUE,
    status_text VARCHAR(100),
    status_category VARCHAR(30)
);

CREATE TABLE fact_race_results (
    race_key INT NOT NULL REFERENCES dim_race(race_key),
    driver_key INT NOT NULL REFERENCES dim_driver(driver_key),
    date_key INT NOT NULL REFERENCES dim_date(date_key),
    constructor_key INT NOT NULL REFERENCES dim_constructor(constructor_key),
    circuit_key INT NOT NULL REFERENCES dim_circuit(circuit_key),
    status_key INT NOT NULL REFERENCES dim_status(status_key),
    result_id INT,
    points DECIMAL(5,2),
    laps_completed SMALLINT,
    is_win SMALLINT,
    is_podium SMALLINT,
    is_points_finish SMALLINT,
    is_dnf SMALLINT,
    grid_position SMALLINT,
    finish_position SMALLINT,
    race_time_ms BIGINT,
    fastest_lap_speed DECIMAL(6,3),
    PRIMARY KEY (race_key, driver_key)
);

CREATE TABLE fact_driver_standings (
    race_key INT NOT NULL REFERENCES dim_race(race_key),
    driver_key INT NOT NULL REFERENCES dim_driver(driver_key),
    date_key INT NOT NULL REFERENCES dim_date(date_key),
    cumulative_points DECIMAL(6,2),
    cumulative_wins SMALLINT,
    standing_position SMALLINT,
    PRIMARY KEY (race_key, driver_key)
);

CREATE TABLE fact_driver_season_entry (
    season_key INT NOT NULL REFERENCES dim_season(season_key),
    driver_key INT NOT NULL REFERENCES dim_driver(driver_key),
    constructor_key INT NOT NULL REFERENCES dim_constructor(constructor_key),
    PRIMARY KEY (season_key, driver_key, constructor_key)
);